import re


def task5(text: str) -> list[str]:
    """Дана строка. Найти все даты, записанные в виде "31 февраля 2007"."""

    month = (
        r"января|февраля|марта|апреля|мая|июня|"
        r"июля|августа|сентября|октября|ноября|декабря"
    )
    pattern = rf"\b(?:0?[1-9]|[12]\d|3[01])\s+(?:{month})\s+\d{{4}}\b"
    return re.findall(pattern, text)


print(task5("Дршки: 31 февраля 2007 и 1 марта 2020, а также 15 июля"))
